#include <test_util.h>

int test_from_list() {
  ZP_Context_t context;
  ZP_Error_t error;
  error = new_context(&context, 32, 48);
  handle_error(error);

  const char* payload1 = "fill";  /* so that the first RegionPointer isn't just 0 */
  ZP_RegionPointer_t pointer1;
  error = ZP_RegionAllocator_alloc(
    &context.region_allocator,
    &pointer1,
    strlen(payload1)
  );
  handle_error(error);
  ZP_RegionAllocator_copy_data(
    &context.region_allocator,
    &pointer1,
    payload1
  );

  ZP_Tagged_t tagged_int1;
  ZP_Int_t int1 = 0x11;
  ZP_Tagged_from_int(&tagged_int1, &int1);

  ZP_Tagged_t tagged_int2;
  ZP_Int_t int2 = 0x22;
  ZP_Tagged_from_int(&tagged_int2, &int2);

  ZP_Tagged_t tagged_int3;
  ZP_Int_t int3 = 0x33;
  ZP_Tagged_from_int(&tagged_int3, &int3);

  ZP_Tagged_t list1;
  ZP_List_new_empty(&list1);

  ZP_Tagged_t list2;
  error = ZP_List_push(&context, &list2, &list1, &tagged_int1);
  handle_error(error);
  ZP_Context_slab_decref(&context, &list1);

  ZP_Tagged_t list3;
  error = ZP_List_push(&context, &list3, &list2, &tagged_int2);
  handle_error(error);
  ZP_Context_slab_decref(&context, &list2);

  ZP_Tagged_t list4;
  error = ZP_List_push(&context, &list4, &list3, &tagged_int3);
  handle_error(error);
  ZP_Context_slab_decref(&context, &list3);

  assert_Context_refcnt(&context, 4, "\x01\x01\x01\x00");
  assert_Context_slab(&context, 32, "\xff\xff\xff\x1f\x11\x00\x00\x40\x00\x00\x00\x10\x22\x00\x00\x40\x01\x00\x00\x10\x33\x00\x00\x40\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x04\x00\x00\x00\x66\x69\x6c\x6c\x24\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");

  ZP_Tagged_t random_access_list;
  error = ZP_RandomAccessList_from_List(
    &context,
    &random_access_list,
    &list4
  );
  handle_error(error);

  assert_Context_refcnt(&context, 4, "\x01\x01\x01\x01");
  assert_Context_slab(&context, 32, "\xff\xff\xff\x1f\x11\x00\x00\x40\x00\x00\x00\x10\x22\x00\x00\x40\x01\x00\x00\x10\x33\x00\x00\x40\x01\x01\x00\x00\x0c\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x04\x00\x00\x00\x66\x69\x6c\x6c\x01\x00\x00\x00\x0c\x00\x00\x00\x11\x00\x00\x40\x22\x00\x00\x40\x33\x00\x00\x40\x10\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00");

  ZP_Context_slab_decref(&context, &list4);

  assert_Context_refcnt(&context, 4, "\x00\x00\x00\x01");
  assert_Context_slab(&context, 32, "\x01\x00\x00\x00\x11\x00\x00\x40\x02\x00\x00\x00\x22\x00\x00\x40\xff\xff\xff\xff\x33\x00\x00\x40\x01\x01\x00\x00\x0c\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x04\x00\x00\x00\x66\x69\x6c\x6c\x01\x00\x00\x00\x0c\x00\x00\x00\x11\x00\x00\x40\x22\x00\x00\x40\x33\x00\x00\x40\x10\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00");

  ZP_Tagged_t random_access_list_increfed;
  ZP_Index_t i;
  for (i = 0;  i < 254;  i++) {
    error = ZP_Context_slab_incref(&context, &random_access_list_increfed, &random_access_list);
    handle_error(error);
  }

  assert_Context_refcnt(&context, 4, "\x00\x00\x00\xff");
  assert_Context_slab(&context, 32, "\x01\x00\x00\x00\x11\x00\x00\x40\x02\x00\x00\x00\x22\x00\x00\x40\xff\xff\xff\xff\x33\x00\x00\x40\x01\x01\x00\x00\x0c\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x04\x00\x00\x00\x66\x69\x6c\x6c\x01\x00\x00\x00\x0c\x00\x00\x00\x11\x00\x00\x40\x22\x00\x00\x40\x33\x00\x00\x40\x10\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00");

  error = ZP_Context_slab_incref(&context, &random_access_list_increfed, &random_access_list);
  handle_error(error);

  assert_Context_refcnt(&context, 4, "\x01\x00\x00\xff");
  assert_Context_slab(&context, 32, "\x01\x01\x00\x00\x0c\x00\x00\x00\x02\x00\x00\x00\x22\x00\x00\x40\xff\xff\xff\xff\x33\x00\x00\x40\x01\x01\x00\x00\x0c\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x04\x00\x00\x00\x66\x69\x6c\x6c\x02\x00\x00\x00\x0c\x00\x00\x00\x11\x00\x00\x40\x22\x00\x00\x40\x33\x00\x00\x40\x10\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00");

  for (i = 0;  i < 254;  i++) {
    ZP_Context_slab_decref(&context, &random_access_list);
  }

  assert_Context_refcnt(&context, 4, "\x01\x00\x00\x01");
  assert_Context_slab(&context, 32, "\x01\x01\x00\x00\x0c\x00\x00\x00\x02\x00\x00\x00\x22\x00\x00\x40\xff\xff\xff\xff\x33\x00\x00\x40\x01\x01\x00\x00\x0c\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x04\x00\x00\x00\x66\x69\x6c\x6c\x02\x00\x00\x00\x0c\x00\x00\x00\x11\x00\x00\x40\x22\x00\x00\x40\x33\x00\x00\x40\x10\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00");

  ZP_Context_slab_decref(&context, &random_access_list);

  assert_Context_refcnt(&context, 4, "\x01\x00\x00\x00");
  assert_Context_slab(&context, 32, "\x01\x01\x00\x00\x0c\x00\x00\x00\x02\x00\x00\x00\x22\x00\x00\x40\xff\xff\xff\xff\x33\x00\x00\x40\x01\x00\x00\x00\x0c\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x04\x00\x00\x00\x66\x69\x6c\x6c\x01\x00\x00\x00\x0c\x00\x00\x00\x11\x00\x00\x40\x22\x00\x00\x40\x33\x00\x00\x40\x10\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00");

  ZP_Context_slab_decref(&context, &random_access_list_increfed);

  assert_Context_refcnt(&context, 4, "\x00\x00\x00\x00");
  assert_Context_slab(&context, 32, "\x03\x00\x00\x00\x0c\x00\x00\x00\x02\x00\x00\x00\x22\x00\x00\x40\xff\xff\xff\xff\x33\x00\x00\x40\x01\x00\x00\x00\x0c\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x04\x00\x00\x00\x66\x69\x6c\x6c\x24\x00\x00\x00\xff\xff\xff\xff\x11\x00\x00\x40\x22\x00\x00\x40\x33\x00\x00\x40\x10\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00");

  return 0;
}

