#include <test_util.h>

int test_add_symbols() {
  ZP_Context_t context;
  ZP_Error_t error;
  error = new_context(&context, 64, 48);
  handle_error(error);

  ZP_Tagged_t symbol1;
  const char* symbol1_data = "one";
  error = ZP_Context_get_symbol(&context, &symbol1, symbol1_data, strlen(symbol1_data));
  handle_error(error);

  assert_Context_refcnt(&context, 8, "\x01\x01\x00\x00\x00\x00\x00\x00");
  assert_Context_slab(&context, 64, "\x00\x01\x00\x00\x00\x00\x00\x00\xff\xff\xff\x1f\x00\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x03\x00\x00\x00\x6f\x6e\x65\x00\x24\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");

  ZP_Tagged_t symbol2;
  const char* symbol2_data = "two";
  error = ZP_Context_get_symbol(&context, &symbol2, symbol2_data, strlen(symbol2_data));
  handle_error(error);

  assert_Context_refcnt(&context, 8, "\x01\x01\x01\x01\x00\x00\x00\x00");
  assert_Context_slab(&context, 64, "\x00\x01\x00\x00\x00\x00\x00\x00\xff\xff\xff\x1f\x00\x00\x00\x30\x00\x01\x00\x00\x0c\x00\x00\x00\x01\x00\x00\x10\x02\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x03\x00\x00\x00\x6f\x6e\x65\x00\x01\x00\x00\x00\x03\x00\x00\x00\x74\x77\x6f\x00\x18\x00\x00\x00\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");

  ZP_Tagged_t symbol3;
  const char* symbol3_data = "three";
  error = ZP_Context_get_symbol(&context, &symbol3, symbol3_data, strlen(symbol3_data));
  handle_error(error);

  assert_Context_refcnt(&context, 8, "\x01\x01\x01\x01\x01\x01\x00\x00");
  assert_Context_slab(&context, 64, "\x00\x01\x00\x00\x00\x00\x00\x00\xff\xff\xff\x1f\x00\x00\x00\x30\x00\x01\x00\x00\x0c\x00\x00\x00\x01\x00\x00\x10\x02\x00\x00\x30\x00\x01\x00\x00\x18\x00\x00\x00\x03\x00\x00\x10\x04\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x03\x00\x00\x00\x6f\x6e\x65\x00\x01\x00\x00\x00\x03\x00\x00\x00\x74\x77\x6f\x00\x01\x00\x00\x00\x05\x00\x00\x00\x74\x68\x72\x65\x65\x00\x6c\x69\x08\x00\x00\x00\xff\xff\xff\xff");

  ZP_Tagged_t symbol2_again;
  error = ZP_Context_get_symbol(&context, &symbol2_again, symbol2_data, strlen(symbol2_data));
  handle_error(error);

  assert_Context_refcnt(&context, 8, "\x01\x01\x02\x01\x01\x01\x00\x00");
  assert_Context_slab(&context, 64, "\x00\x01\x00\x00\x00\x00\x00\x00\xff\xff\xff\x1f\x00\x00\x00\x30\x00\x01\x00\x00\x0c\x00\x00\x00\x01\x00\x00\x10\x02\x00\x00\x30\x00\x01\x00\x00\x18\x00\x00\x00\x03\x00\x00\x10\x04\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x03\x00\x00\x00\x6f\x6e\x65\x00\x01\x00\x00\x00\x03\x00\x00\x00\x74\x77\x6f\x00\x01\x00\x00\x00\x05\x00\x00\x00\x74\x68\x72\x65\x65\x00\x6c\x69\x08\x00\x00\x00\xff\xff\xff\xff");

  assert(symbol2.data, symbol2_again.data);

  assert_Context_refcnt(&context, 8, "\x01\x01\x02\x01\x01\x01\x00\x00");
  assert_Context_slab(&context, 64, "\x00\x01\x00\x00\x00\x00\x00\x00\xff\xff\xff\x1f\x00\x00\x00\x30\x00\x01\x00\x00\x0c\x00\x00\x00\x01\x00\x00\x10\x02\x00\x00\x30\x00\x01\x00\x00\x18\x00\x00\x00\x03\x00\x00\x10\x04\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x01\x00\x00\x00\x03\x00\x00\x00\x6f\x6e\x65\x00\x01\x00\x00\x00\x03\x00\x00\x00\x74\x77\x6f\x00\x01\x00\x00\x00\x05\x00\x00\x00\x74\x68\x72\x65\x65\x00\x6c\x69\x08\x00\x00\x00\xff\xff\xff\xff");

  ZP_Context_slab_decref(&context, &symbol1);

  assert_Context_refcnt(&context, 8, "\x00\x00\x02\x01\x01\x01\x00\x00");
  assert_Context_slab(&context, 64, "\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x30\x00\x01\x00\x00\x0c\x00\x00\x00\xff\xff\xff\x1f\x02\x00\x00\x30\x00\x01\x00\x00\x18\x00\x00\x00\x03\x00\x00\x10\x04\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x0c\x00\x00\x00\x28\x00\x00\x00\x6f\x6e\x65\x00\x01\x00\x00\x00\x03\x00\x00\x00\x74\x77\x6f\x00\x01\x00\x00\x00\x05\x00\x00\x00\x74\x68\x72\x65\x65\x00\x6c\x69\x08\x00\x00\x00\xff\xff\xff\xff");

  ZP_Context_slab_decref(&context, &symbol3);

  assert_Context_refcnt(&context, 8, "\x00\x00\x02\x01\x00\x00\x00\x00");
  assert_Context_slab(&context, 64, "\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x30\x00\x01\x00\x00\x0c\x00\x00\x00\xff\xff\xff\x1f\x02\x00\x00\x30\x01\x00\x00\x00\x18\x00\x00\x00\x04\x00\x00\x00\x04\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x0c\x00\x00\x00\x18\x00\x00\x00\x6f\x6e\x65\x00\x01\x00\x00\x00\x03\x00\x00\x00\x74\x77\x6f\x00\x18\x00\x00\x00\xff\xff\xff\xff\x74\x68\x72\x65\x65\x00\x6c\x69\x08\x00\x00\x00\xff\xff\xff\xff");

  ZP_Context_slab_decref(&context, &symbol2);

  assert_Context_refcnt(&context, 8, "\x00\x00\x01\x01\x00\x00\x00\x00");
  assert_Context_slab(&context, 64, "\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x30\x00\x01\x00\x00\x0c\x00\x00\x00\xff\xff\xff\x1f\x02\x00\x00\x30\x01\x00\x00\x00\x18\x00\x00\x00\x04\x00\x00\x00\x04\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x0c\x00\x00\x00\x18\x00\x00\x00\x6f\x6e\x65\x00\x01\x00\x00\x00\x03\x00\x00\x00\x74\x77\x6f\x00\x18\x00\x00\x00\xff\xff\xff\xff\x74\x68\x72\x65\x65\x00\x6c\x69\x08\x00\x00\x00\xff\xff\xff\xff");

  ZP_Context_slab_decref(&context, &symbol2_again);

  assert_Context_refcnt(&context, 8, "\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_slab(&context, 64, "\xff\xff\xff\xff\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x30\x05\x00\x00\x00\x0c\x00\x00\x00\x02\x00\x00\x00\x02\x00\x00\x30\x01\x00\x00\x00\x18\x00\x00\x00\x04\x00\x00\x00\x04\x00\x00\x30\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
  assert_Context_region(&context, 48, "\x30\x00\x00\x00\xff\xff\xff\xff\x6f\x6e\x65\x00\x0c\x00\x00\x00\x18\x00\x00\x00\x74\x77\x6f\x00\x18\x00\x00\x00\xff\xff\xff\xff\x74\x68\x72\x65\x65\x00\x6c\x69\x08\x00\x00\x00\xff\xff\xff\xff");

  return 0;
}

